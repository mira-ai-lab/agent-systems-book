"""Memory retrieval with hybrid dense and sparse search.

Dense retrieval uses vector search over embeddings generated by the
configured embedding model, capturing semantic similarity.

Sparse retrieval uses ``BM25Okapi`` with jieba tokenization, capturing exact
keyword and entity matches.

The two rankings are combined with Reciprocal Rank Fusion (RRF), then adjusted
by vector similarity, time decay, and importance.

:author: zhanghong, liuhui
:date: 2026-11-14
"""

from __future__ import annotations

from datetime import datetime
from typing import Any

import numpy as np
from rank_bm25 import BM25Okapi

from memory_store import MemoryStore

try:
    import jieba

    def tokenize_for_bm25(text: str) -> list[str]:
        """Tokenize Chinese and English text for BM25 with jieba."""
        return [token.strip() for token in jieba.cut(text.lower()) if token.strip()]

except ImportError:

    def tokenize_for_bm25(text: str) -> list[str]:
        """Split text on whitespace when jieba is unavailable."""
        return text.lower().split()


class HybridRetriever:
    """Fuse vector and BM25 rankings with reciprocal rank fusion."""

    def __init__(self, k1: float = 1.5, b: float = 0.75, rrf_k: int = 60) -> None:
        self.bm25: BM25Okapi | None = None
        self.documents: list[str] = []
        self.k1 = k1
        self.b = b
        self.rrf_k = rrf_k

    def fit(self, documents: list[str]) -> None:
        """Build the BM25 index.

        Args:
            documents: Documents ordered by their local index.
        """
        self.documents = list(documents)
        tokenized_documents = [tokenize_for_bm25(document) for document in documents]
        self.bm25 = BM25Okapi(tokenized_documents, k1=self.k1, b=self.b)

    def search(
        self,
        query: str,
        dense_scores: list[tuple[int, float]],
        top_k: int = 5,
    ) -> list[tuple[int, float]]:
        """Fuse vector and BM25 rankings into document indexes and RRF scores.

        The order of ``dense_scores`` defines the vector ranking. Its
        similarity values are used only to determine rank; the retriever
        combines them with vector similarity when calculating final scores.
        """
        if not self.bm25 or not self.documents:
            return [
                (index, 1.0 / (self.rrf_k + rank))
                for rank, (index, _) in enumerate(dense_scores[:top_k])
            ]

        bm25_scores = self.bm25.get_scores(tokenize_for_bm25(query))
        bm25_ranked = np.argsort(bm25_scores)[::-1]

        rrf_scores: dict[int, float] = {}
        for rank, (index, _) in enumerate(dense_scores):
            rrf_scores[index] = rrf_scores.get(index, 0.0) + 1.0 / (
                self.rrf_k + rank
            )
        for rank, index in enumerate(bm25_ranked):
            if bm25_scores[index] > 0:
                rrf_scores[int(index)] = rrf_scores.get(int(index), 0.0) + 1.0 / (
                    self.rrf_k + rank
                )

        return sorted(
            rrf_scores.items(),
            key=lambda item: item[1],
            reverse=True,
        )[:top_k]


class MemoryRetriever:
    """Hybrid retriever for user-profile facts and preference memories."""

    def __init__(
        self,
        store: MemoryStore,
        *,
        hybrid_retriever: HybridRetriever | None = None,
        top_k: int = 5,
        similarity_threshold: float = 0.0,
        time_decay_factor: float = 0.95,
    ) -> None:
        self.store = store
        self.hybrid_retriever = hybrid_retriever or HybridRetriever()
        self.top_k = top_k
        self.similarity_threshold = similarity_threshold
        self.time_decay_factor = time_decay_factor

    def dense_search(
        self,
        query: str,
        user_id: str,
        top_k: int = 5,
    ) -> list[dict[str, Any]]:
        """Run dense retrieval and return candidates with similarity and metadata."""
        if not self.store.documents:
            return []
        dense = self.store.collection.query(
            query_texts=[query],
            n_results=top_k,
            where={"user_id": user_id},
        )
        ids = (dense.get("ids") or [[]])[0]
        distances = (dense.get("distances") or [[]])[0]
        documents = (dense.get("documents") or [[]])[0]
        metadatas = (dense.get("metadatas") or [[]])[0]
        return [
            {
                "id": memory_id,
                "distance": distance,
                "vector_sim": MemoryStore.distance_to_similarity(distance),
                "content": document,
                "metadata": metadata or {},
            }
            for memory_id, distance, document, metadata in zip(
                ids,
                distances,
                documents,
                metadatas,
            )
        ]

    def search(
        self,
        query: str,
        *,
        user_id: str | None = None,
        memory_types: list[str] | None = None,
        top_k: int | None = None,
        use_time_decay: bool = True,
        use_importance_weight: bool = True,
    ) -> list[dict[str, Any]]:
        """Retrieve user-profile facts and preference memories relevant to a query.

        Args:
            query: Current user question.
            user_id: User identifier. Defaults to the store's user ID.
            memory_types: Optional memory-type filter.
            top_k: Number of results. Defaults to the retriever's configured
                value.
            use_time_decay: Whether to apply time decay.
            use_importance_weight: Whether to apply importance weighting.

        Returns:
            Memory records sorted by descending ``final_score``.
        """
        resolved_user_id = user_id or self.store.user_id
        limit = top_k or self.top_k
        records = self.store.get_user_records(resolved_user_id, memory_types)
        if not records:
            return []

        documents = [
            record.get("content") or record.get("summary", "")
            for record in records
        ]
        self.hybrid_retriever.fit(documents)
        dense_records = self.dense_search(query, resolved_user_id, limit * 2)
        id_to_local_index = {
            record["id"]: index for index, record in enumerate(records)
        }
        dense_scores: list[tuple[int, float]] = []
        vector_scores: dict[int, float] = {}
        for dense_record in dense_records:
            index = id_to_local_index.get(dense_record["id"])
            if index is None:
                continue
            vector_similarity = dense_record["vector_sim"]
            dense_scores.append((index, vector_similarity))
            vector_scores[index] = vector_similarity

        hybrid_results = self.hybrid_retriever.search(
            query,
            dense_scores,
            limit * 2,
        )
        results: list[dict[str, Any]] = []
        for index, rrf_score in hybrid_results:
            record = records[index]
            vector_similarity = vector_scores.get(index, 0.0)
            score = rrf_score * vector_similarity
            if use_time_decay:
                score *= self._time_decay(
                    str(record.get("timestamp") or datetime.now().isoformat())
                )
            if use_importance_weight:
                score *= 0.5 + float(record.get("importance", 0.5))
            if score < self.similarity_threshold:
                continue
            results.append(
                {
                    **record,
                    "vector_sim": vector_similarity,
                    "rrf_score": rrf_score,
                    "final_score": score,
                    "score": score,
                }
            )
        return sorted(
            results,
            key=lambda item: item["final_score"],
            reverse=True,
        )[:limit]

    def _time_decay(self, timestamp: str) -> float:
        """Calculate an exponential decay weight from the memory timestamp."""
        try:
            days = (datetime.now() - datetime.fromisoformat(timestamp)).days
        except ValueError:
            days = 0
        return self.time_decay_factor ** max(days, 0)
