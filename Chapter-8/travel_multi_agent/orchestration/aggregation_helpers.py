"""Aggregation helpers: select the final response from subtask results.

The final response is selected in code (not generated by an LLM), matching
Chapter-6's ``compose_final_response``.

:author: zhanghong, liuhui, xingrui
:date: 2026-11-22
"""

from __future__ import annotations

import json
from typing import Any, Dict, List


def is_single_direct_response(results: Dict[str, Any]) -> bool:
    """Return whether there is exactly one subtask result."""
    return len(results) == 1


def direct_response_from_results(results: Dict[str, Any]) -> str:
    """Extract the user-facing response from a single subtask result."""
    result = next(iter(results.values()))
    summary = (result.get("agent_summary") or "").strip()
    if summary:
        return summary
    tool_data = result.get("tool_data")
    if tool_data is not None:
        return json.dumps(tool_data, ensure_ascii=False, indent=2)
    return json.dumps(result, ensure_ascii=False, indent=2)


def compose_final_response(
    results: Dict[str, Any],
    execution_order: List[str],
) -> str:
    """Select the final response from subtask results without an LLM."""
    if is_single_direct_response(results):
        return direct_response_from_results(results)

    final_result = next(
        (
            results[task_id]
            for task_id in reversed(execution_order)
            if isinstance(results.get(task_id), dict)
            and (results[task_id].get("agent_summary") or "").strip()
        ),
        None,
    )
    if final_result:
        return final_result["agent_summary"].strip()

    summaries = [
        (result.get("agent_summary") or "").strip()
        for result in results.values()
        if isinstance(result, dict) and (result.get("agent_summary") or "").strip()
    ]
    return "\n\n".join(summaries) or "未获得可用的领域结果。"